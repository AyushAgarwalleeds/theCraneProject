// Run after both Arduino builds. The role flag is recorded by arduino-cli.
import {readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {join} from 'node:path';

const [sender, receiver] = process.argv.slice(2);
if (!sender || !receiver) throw Error('Usage: node tools/package-firmware.mjs SENDER_BUILD RECEIVER_BUILD');
const root = new URL('../docs/firmware/', import.meta.url);
const source = readFileSync(new URL('../CraneLink_PhoneBench/RadioLink.h', import.meta.url), 'utf8');
const release = source.match(/constexpr unsigned firmwareRelease = (\d+);/)[1];
const files = {
  'bootloader.bin':'CraneLink_PhoneBench.ino.bootloader.bin',
  'partitions.bin':'CraneLink_PhoneBench.ino.partitions.bin',
  'boot_app0.bin':'boot_app0.bin',
  'app.bin':'CraneLink_PhoneBench.ino.bin',
};
const manifest = {}, outputs = [];
for (const [role, directory] of Object.entries({sender, receiver})) {
  const options = JSON.parse(readFileSync(join(directory, 'build.options.json'), 'utf8'));
  if (options.fqbn !== 'esp32:esp32:esp32' ||
      options.customBuildProperties !== 'build.extra_flags=-DCRANELINK_SENDER=' + Number(role === 'sender'))
    throw Error('Unexpected target or role in ' + directory);
  manifest[role] = {};
  for (const [name, built] of Object.entries(files)) {
    const data = readFileSync(join(directory, built));
    if (!data.length || (name === 'app.bin' && data[0] !== 0xe9)) throw Error('Invalid image in ' + directory);
    const hash = algorithm => createHash(algorithm).update(data).digest('hex');
    manifest[role][name] = {bytes:data.length, sha256:hash('sha256'), md5:hash('md5')};
    outputs.push([new URL(role + '/' + name, root), data]);
  }
}
for (const [path, data] of outputs) writeFileSync(path, data);
writeFileSync(new URL('release-' + release + '.mjs', root),
  '// Generated by tools/package-firmware.mjs.\nexport const firmwareImages = ' + JSON.stringify(manifest, null, 2) + ';\n');
